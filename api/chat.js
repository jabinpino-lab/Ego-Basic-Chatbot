function json(res, status, body) {
  res.status(status).setHeader('Content-Type', 'application/json');
  res.end(JSON.stringify(body));
}

function normalizeMessages(messages) {
  return (Array.isArray(messages) ? messages : []).map((m) => ({
    role: m.role === 'assistant' ? 'assistant' : 'user',
    content: String(m.content || ''),
    image:
      typeof m.image === 'string' && m.image.startsWith('data:image/')
        ? m.image
        : null
  }));
}

async function callGemini(messages) {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is not configured.');
  }

  const contents = messages.map((m) => {
    const parts = [];

    if (m.content) {
      parts.push({ text: m.content });
    }

    if (m.image) {
      const match = m.image.match(
        /^data:(image\/[a-zA-Z0-9.+-]+);base64,(.+)$/
      );

      if (match) {
        parts.push({
          inline_data: {
            mime_type: match[1],
            data: match[2]
          }
        });
      }
    }

    return {
      role: m.role === 'assistant' ? 'model' : 'user',
      parts: parts.length ? parts : [{ text: '' }]
    };
  });

  const response = await fetch(
    'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-lite:generateContent?key=' +
      encodeURIComponent(apiKey),
    {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        system_instruction: {
          parts: [{ text: EGO_SYSTEM_PROMPT }]
        },
        contents,
        generationConfig: {
          temperature: 0.15,
          maxOutputTokens: 1200
        }
      })
    }
  );

  const data = await response.json();

  if (!response.ok) {
    throw new Error(
      data?.error?.message || 'Gemini request failed.'
    );
  }

  const text = data?.candidates?.[0]?.content?.parts
    ?.map((p) => p.text || '')
    .join('')
    .trim();

  if (!text) {
    throw new Error('Gemini returned an empty response.');
  }

  return text;
}

async function callOpenRouter(messages) {
  const apiKey = process.env.OPENROUTER_API_KEY;

  if (!apiKey) {
    throw new Error('OPENROUTER_API_KEY is not configured.');
  }

  const payload = messages.map((m) => ({
    role: m.role,
    content: m.image
      ? [
          {
            type: 'text',
            text: m.content
          },
          {
            type: 'image_url',
            image_url: {
              url: m.image
            }
          }
        ]
      : m.content
  }));

  const response = await fetch(
    'https://openrouter.ai/api/v1/chat/completions',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json',
        'HTTP-Referer':
          process.env.SITE_URL ||
          'https://ego-chatbot-1.vercel.app',
        'X-Title':
          'EGO Physical AI Annotation Assistant'
      },
      body: JSON.stringify({
        model: 'openrouter/free',
        messages: [
          {
            role: 'system',
            content: EGO_SYSTEM_PROMPT
          },
          ...payload
        ],
        temperature: 0.15,
        max_tokens: 1200
      })
    }
  );

  const data = await response.json();

  if (!response.ok) {
    throw new Error(
      data?.error?.message || 'OpenRouter request failed.'
    );
  }

  const text = data?.choices?.[0]?.message?.content;

  if (!text) {
    throw new Error('OpenRouter returned an empty response.');
  }

  return typeof text === 'string'
    ? text
    : JSON.stringify(text);
}

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return json(res, 405, {
      error: 'Method not allowed.'
    });
  }

  try {
    const messages = normalizeMessages(
      req.body?.messages
    );

    if (!messages.length) {
      return json(res, 400, {
        error: 'No messages supplied.'
      });
    }

    let text;
    let provider = 'gemini';

    try {
      text = await callGemini(messages);
    } catch (geminiError) {
      console.error(
        'Gemini failed:',
        geminiError?.message
      );

      if (!process.env.OPENROUTER_API_KEY) {
        throw geminiError;
      }

      provider = 'openrouter';
      text = await callOpenRouter(messages);
    }

    return json(res, 200, {
      text,
      provider
    });
  } catch (error) {
    console.error(
      'EGO assistant error:',
      error
    );

    return json(res, 500, {
      error:
        error?.message ||
        'Assistant request failed.'
    });
  }
}
